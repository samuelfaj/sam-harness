func githubWorkflow(cfg model.Config) string {
	var builder strings.Builder
	builder.WriteString(`# Generated by sam-harness. Edit .sam-harness/config.yaml, not this file.
name: sam-harness

on:
  pull_request:
  push:
    branches: [main]

permissions:
  contents: read

jobs:
  check:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@11d5960a326750d5838078e36cf38b85af677262 # v4
      - uses: actions/setup-go@924ae3a1cded613372ab5595356fb5720e22ba16 # v6
        with:
          go-version: "1.27.0"
`)
	for index, setup := range cfg.CI.SetupCommands["github"] {
		builder.WriteString(fmt.Sprintf("      - name: Prepare repository %d\n        working-directory: %s\n        run: %s\n", index+1, yamlSingle(setup.Workdir), yamlSingle(shellJoin(setup.Command))))
	}
	builder.WriteString(`      - name: Run configured gates
        run: go run github.com/samuelfaj/sam-harness/cmd/sam-harness@v0.1.0 check . --format human
`)
	return builder.String()
}

func gitlabJob(cfg model.Config) string {
	image := cfg.CI.GitLabImage
	if image == "" {
		image = "golang:1.27-alpine"
	}
	var builder strings.Builder
	builder.WriteString(fmt.Sprintf(`# Generated by sam-harness. Edit .sam-harness/config.yaml, not this file.
sam-harness:
  image: %s
  stage: test
  script:
`, yamlSingle(image)))
	for _, setup := range cfg.CI.SetupCommands["gitlab"] {
		command := shellJoin(setup.Command)
		if setup.Workdir != "." {
			command = "cd " + shellQuote(setup.Workdir) + " && " + command
		}
		builder.WriteString("    - " + yamlSingle(command) + "\n")
	}
	builder.WriteString(`    - 'go run github.com/samuelfaj/sam-harness/cmd/sam-harness@v0.1.0 check . --format human'
  rules:
    - if: $CI_COMMIT_BRANCH
`)
	return builder.String()
}

func shellJoin(command []string) string {
	quoted := make([]string, len(command))
	for index, argument := range command {
		quoted[index] = shellQuote(argument)
	}
	return strings.Join(quoted, " ")
}

func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'"
}

func yamlSingle(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "''") + "'"
}

