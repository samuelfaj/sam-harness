func githubAgentsWorkflow(cfg model.Config) string {
	control := cfg.CI.AgentControlPlanes["github"]
	reviewBound := len(scopedSecretBindings(cfg, "github", model.CISecretScopeReview)) > 0
	repairSecretBound := repairEnabled(cfg) && len(scopedSecretBindings(cfg, "github", model.CISecretScopeRepair)) > 0
	repairReview := repairEnabled(cfg) && reviewBound
	var builder strings.Builder
	builder.WriteString(`# Generated by sam-harness. Edit .sam-harness/config.yaml, not this file.
# SECURITY: pull_request_target and repository_dispatch load this definition from the trusted default branch.
# Never execute target setup, hooks, caches, local actions, or repository commands in a secret-bearing job.
name: sam-harness agents

on:
`)
	var resolveConditions []string
	if reviewBound {
		builder.WriteString(`  pull_request_target:
    types: [opened, synchronize, reopened, ready_for_review]
  repository_dispatch:
    types: [sam_harness_merge_group_review]
`)
		resolveConditions = append(resolveConditions, "github.event_name == 'pull_request_target'", "github.event_name == 'repository_dispatch'")
	}
	if repairSecretBound {
		builder.WriteString(`  workflow_run:
    workflows: [sam-harness]
    types: [completed]
`)
		resolveConditions = append(resolveConditions, "(github.event_name == 'workflow_run' && github.event.workflow_run.conclusion == 'failure' && github.event.workflow_run.event == 'pull_request')")
	}
	builder.WriteString(`
permissions:
  contents: read

jobs:
  resolve:
    if: ` + strings.Join(resolveConditions, " || ") + `
    runs-on: ubuntu-latest
    environment:
      name: ` + yamlSingle(cfg.CI.AgentSecretEnvironments["github"]) + `
    outputs:
      head_sha: ${{ steps.identity.outputs.head_sha }}
      base_sha: ${{ steps.identity.outputs.base_sha }}
      pr_number: ${{ steps.identity.outputs.pr_number }}
      source_run_id: ${{ steps.identity.outputs.source_run_id }}
      head_ref: ${{ steps.identity.outputs.head_ref }}
    steps:
      - name: Create least-privilege GitHub App identity token
        id: app-token
        uses: actions/create-github-app-token@fee1f7d63c2ff003460e3d139729b119787bc349 # v2.2.2
        with:
          app-id: ${{ secrets.` + control.AppIDSecret + ` }}
          private-key: ${{ secrets.` + control.AppPrivateKeySecret + ` }}
          permission-contents: read
          permission-pull-requests: read
      - name: Resolve exact provider-owned pull request identity
        id: identity
        env:
          GH_TOKEN: ${{ steps.app-token.outputs.token }}
          EVENT_KIND: ${{ github.event_name }}
          EVENT_HEAD_SHA: ${{ github.event.pull_request.head.sha || github.event.client_payload.head_sha || github.event.workflow_run.head_sha }}
          EVENT_BASE_SHA: ${{ github.event.pull_request.base.sha || github.event.client_payload.base_sha }}
          EVENT_HEAD_REF: ${{ github.event.client_payload.merge_group_ref }}
          EVENT_PR_NUMBER: ${{ github.event.pull_request.number }}
          SOURCE_RUN_ID: ${{ github.event.workflow_run.id }}
        run: |
          set -eu
          head_sha="$EVENT_HEAD_SHA"
          pr_number="$EVENT_PR_NUMBER"
          head_ref="$EVENT_HEAD_REF"
          if [ "$EVENT_KIND" = workflow_run ]; then
            pulls="$(gh api "repos/${GITHUB_REPOSITORY}/commits/${head_sha}/pulls")"
            test "$(printf '%s' "$pulls" | jq 'length')" -eq 1 || { echo 'triggering head must resolve to exactly one current pull request' >&2; exit 1; }
            pr_number="$(printf '%s' "$pulls" | jq -r '.[0].number')"
          fi
          if [ "$EVENT_KIND" = repository_dispatch ]; then
            case "$EVENT_HEAD_REF" in
              refs/heads/gh-readonly-queue/*) ;;
              *) echo 'repository dispatch must name a provider-owned merge-queue ref' >&2; exit 1 ;;
            esac
            printf '%s\n' "$head_sha" | grep -Eq '^[0-9a-fA-F]{40}([0-9a-fA-F]{24})?$'
            printf '%s\n' "$EVENT_BASE_SHA" | grep -Eq '^[0-9a-fA-F]{40}([0-9a-fA-F]{24})?$'
            base_sha="$EVENT_BASE_SHA"
            current_head="$(gh api "repos/${GITHUB_REPOSITORY}/git/ref/${EVENT_HEAD_REF#refs/}" --jq .object.sha)"
            test "$current_head" = "$head_sha" || { echo 'merge-group head drifted before trusted agent execution' >&2; exit 1; }
            default_branch="$(gh api "repos/${GITHUB_REPOSITORY}" --jq .default_branch)"
            current_base="$(gh api "repos/${GITHUB_REPOSITORY}/git/ref/heads/${default_branch}" --jq .object.sha)"
            test "$current_base" = "$base_sha" || { echo 'merge-group base drifted before trusted agent execution' >&2; exit 1; }
          else
            test -n "$pr_number"
            pull="$(gh api "repos/${GITHUB_REPOSITORY}/pulls/${pr_number}")"
            current_head="$(printf '%s' "$pull" | jq -r '.head.sha')"
            base_sha="$(printf '%s' "$pull" | jq -r '.base.sha')"
            head_ref="$(printf '%s' "$pull" | jq -r '.head.ref')"
            test "$current_head" = "$head_sha" || { echo 'pull request head drifted before trusted agent execution' >&2; exit 1; }
          fi
          printf '%s\n' "$head_sha" | grep -Eq '^[0-9a-fA-F]{40}([0-9a-fA-F]{24})?$'
          printf '%s\n' "$base_sha" | grep -Eq '^[0-9a-fA-F]{40}([0-9a-fA-F]{24})?$'
          if [ "$EVENT_KIND" = pull_request_target ]; then
            test "$base_sha" = "$EVENT_BASE_SHA"
          fi
          printf 'head_sha=%s\nbase_sha=%s\npr_number=%s\nsource_run_id=%s\nhead_ref=%s\n' "$head_sha" "$base_sha" "$pr_number" "$SOURCE_RUN_ID" "$head_ref" >> "$GITHUB_OUTPUT"
`)
	if reviewBound {
		writeGitHubTrustedReviewControlPlane(&builder, cfg, control)
	}
	if repairReview || repairSecretBound {
		writeGitHubTrustedRepairControlPlane(&builder, cfg, repairReview, repairSecretBound)
	}
	return builder.String()
}

