	if localRepair {
		writeGitHubRepairJobs(&builder, cfg, localReview)
	}
	if localRepair && repairChangeRequestEnabled(cfg) {
		writeGitHubRepairPublisherJob(&builder, cfg, localReview)
	}
	writeGitHubPhaseJob(&builder, cfg, "staging", model.PhaseStaging, "artifact", "staging")
