func releaseRunbook(cfg model.Config) string {
	return fmt.Sprintf(`# Release and rollback

Rollback owner: %s
Observation window: %s

1. Freeze the reviewed commit and produce one immutable artifact.
2. Record the artifact digest, SBOM, provenance, test receipts, and approvals.
3. Promote the same digest between environments. Never rebuild for production.
4. Use a canary or staged rollout calibrated to traffic, risk, and response capacity.
5. Stop promotion when technical or business health gates fail.
6. Roll back code only when stored data remains compatible. Otherwise use the tested forward-fix or recovery plan.
7. Keep the observation window open until the configured owner accepts the live evidence.
`, valueOr(cfg.Release.RollbackOwner, "unassigned"), valueOr(cfg.Release.ObservationWindow, "not calibrated"))
}

func migrationRunbook(cfg model.Config) string {
	return `# Data migration

1. Name the authoritative source and every producer and consumer.
2. Version contracts and keep N and N-1 compatibility during transition.
3. Make backfills resumable and idempotent. Record checkpoints.
4. Define ordering, duplicate, deletion, and partial-failure semantics.
5. Reconcile by record and invariant, not aggregate counts alone.
6. Cut consumers over independently behind measured gates.
7. Test restore, forward fix, and rollback without resurrecting deleted or stale data.
8. Contract the old path only after signed reconciliation criteria pass.
`
}

