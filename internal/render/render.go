func deploymentPhase(phase model.Phase) bool {
	return phase == model.PhaseStaging || phase == model.PhaseMigration || phase == model.PhaseProduction || phase == model.PhaseObserve || phase == model.PhaseRollback
}

func untrustedPhase(phase model.Phase) bool {
	return phase == model.PhaseStatic || phase == model.PhaseTest || phase == model.PhaseArtifact
}

func phaseAuthorizedForCI(cfg model.Config, phase model.Phase) bool {
	switch phase {
	case model.PhaseReview:
		return cfg.Authority.Network
	case model.PhaseStaging, model.PhaseMigration:
		return cfg.Authority.Network && cfg.Authority.Deploy
	case model.PhaseProduction, model.PhaseRollback:
		return cfg.Authority.Network && cfg.Authority.Deploy && cfg.Authority.Release
	case model.PhaseObserve:
		// Observe is chained after production in generated CI. Keeping it behind
		// deploy authority prevents an orphaned post-deployment job while still
		// matching the runtime's network requirement.
		return cfg.Authority.Network && cfg.Authority.Deploy
	default:
		return true
	}
}

func scopedSecretBindings(cfg model.Config, provider, scope string) []model.CISecretBinding {
	var bindings []model.CISecretBinding
	for _, binding := range cfg.CI.SecretBindings[provider] {
		if binding.Scope == scope {
			bindings = append(bindings, binding)
		}
	}
	sort.Slice(bindings, func(left, right int) bool {
		if bindings[left].Environment == bindings[right].Environment {
			return bindings[left].Secret < bindings[right].Secret
		}
		return bindings[left].Environment < bindings[right].Environment
	})
	return bindings
}

func writeGitHubStepSecretEnv(builder *strings.Builder, cfg model.Config, scope string) {
	bindings := scopedSecretBindings(cfg, "github", scope)
	if len(bindings) == 0 {
		return
	}
	builder.WriteString("        env:\n")
	for _, binding := range bindings {
		builder.WriteString(fmt.Sprintf("          %s: ${{ secrets.%s }}\n", binding.Environment, binding.Secret))
	}
}

func gitLabCommandWithSecrets(cfg model.Config, scope, command string) string {
	bindings := scopedSecretBindings(cfg, "gitlab", scope)
	if len(bindings) == 0 {
		return command
	}
	var prefix strings.Builder
	prefix.WriteString("env")
	for _, binding := range bindings {
		prefix.WriteString(" ")
		prefix.WriteString(binding.Environment)
		prefix.WriteString("=\"${")
		prefix.WriteString(binding.Secret)
		prefix.WriteString("}\"")
	}
	return prefix.String() + " " + command
}

