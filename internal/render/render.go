func writeGuardInventory(builder *strings.Builder, guards model.GuardSet, categories []string) {
	for _, category := range categories {
		if command, ok := guards.Commands[category]; ok {
			writeCommandInventory(builder, category+" command", command)
			continue
		}
		if waiver := strings.TrimSpace(guards.Waivers[category]); waiver != "" {
			builder.WriteString(fmt.Sprintf("- %s waiver: %s\n", category, waiver))
			continue
		}
		builder.WriteString(fmt.Sprintf("- %s: missing command or auditable waiver\n", category))
	}
}

func writeGateInventory(builder *strings.Builder, gates []model.Gate, phase model.Phase) {
	count := 0
	for _, gate := range gates {
		gatePhase := gate.Phase
		if gatePhase == "" {
			gatePhase = model.PhaseStatic
		}
		if gatePhase != phase {
			continue
		}
		count++
		builder.WriteString(fmt.Sprintf("- %s `%s` in `%s`: `%s`\n", phase, gate.Name, gate.Workdir, shellJoin(gate.Command)))
	}
	if count == 0 {
		builder.WriteString(fmt.Sprintf("- %s: not configured\n", phase))
	}
}

